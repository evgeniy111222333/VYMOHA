export function cpvDivision(code: string | null | undefined): string | null {
  if (!code) return null;
  return code.replace(/\D/g, "").slice(0, 2) || null;
}

export function cpvDivisionName(code: string | null | undefined): string | null {
  const division = cpvDivision(code);
  return division ? (CPV_DIVISIONS[division] ?? null) : null;
}
