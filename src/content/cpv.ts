export function cpvClass(code: string | null | undefined): string | null {
  if (!code) return null;
  const digits = code.replace(/\D/g, "");
  return digits.length >= 5 ? digits.slice(0, 5) : null;
}

export function cpvClassName(code: string | null | undefined): string | null {
  const cls = cpvClass(code);
  return cls ? (CPV_CLASSES[cls] ?? null) : null;
}
